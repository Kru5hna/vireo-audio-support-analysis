"""
src/analysis.py
Performs the core business and econometric analysis for Vireo Audio:
1. Tests Priya Raman's hiring rule ("most volume gets next two hires") against operational realities.
2. Derives the formal Business Goal Number in Rupees using strictly policy-defined cost standards.
3. Quantifies headcount workload, resolution times, breach rates, and financial leakage.
"""

import os
import sys
import pandas as pd
import numpy as np

sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), '..')))

# Policy defined cost standards (support-policy.pdf §3, §4, §5)
TRANSFER_COST_INR = 305.0
SLA_BREACH_PENALTY_INR = 350.0
AGENT_HOURLY_WAGE_INR = 165.0
SHIFT_HOURS = 8.0
ANNUAL_TWO_HIRES_COST_INR = 900000.0  # From Finance Controller Arjun Mehta's email

TEAM_HEADCOUNTS = {
    'Chat Frontline': 15,
    'Email Frontline': 7,
    'Escalations & Warranty': 6,
    'Logistics': 5,
    'Voice Frontline': 4,
    'Billing': 4,
    'Returns Desk': 3
}

def analyze_headcount_rule(df):
    """
    Directly tests Priya's rule:
    'Whichever team has the most volume gets the next two hires.'
    Evaluates assigned demand vs true resolved workload, per-agent load, resolution time, and breaches.
    """
    core = df[df['created_at'] >= '2025-01-01'].copy()

    assigned_counts = core['assigned_team'].value_counts()
    resolved_counts = core['resolving_team'].value_counts()
    median_res_time = core.groupby('resolving_team')['resolution_hours'].median()
    breach_rates = core.groupby('assigned_team')['is_sla_breach'].mean()
    transfers_out = core.groupby('assigned_team')['transfers_recorded'].sum()

    comparison = []
    for team, agents in TEAM_HEADCOUNTS.items():
        assigned = assigned_counts.get(team, 0)
        resolved = resolved_counts.get(team, 0)
        per_agent = resolved / agents
        res_hours = median_res_time.get(team, 0.0)
        breach_pct = breach_rates.get(team, 0.0) * 100.0
        xfer_out = transfers_out.get(team, 0)

        comparison.append({
            'Team': team,
            'Agent_Headcount': agents,
            'Intake_Assigned_Volume': assigned,
            'Assigned_Share': f"{assigned / len(core) * 100:.1f}%",
            'Actually_Resolved_Volume': resolved,
            'Resolved_Share': f"{resolved / len(core) * 100:.1f}%",
            'Tickets_Per_Agent': round(per_agent, 1),
            'Median_Resolution_Hours': round(res_hours, 2),
            'SLA_Breach_Rate_Pct': round(breach_pct, 2),
            'Transfers_Generated': int(xfer_out)
        })

    summary_df = pd.DataFrame(comparison).sort_values('Actually_Resolved_Volume', ascending=False)
    return summary_df


def compute_business_goal(df):
    """
    Derives the formal Business Goal Number with hard rupee arithmetic:
    Focus:
    1. Eradicate Billing intake misrouting (cuts transfers & SLA breach penalties).
    2. Eliminate dual refund-replacement leakage.
    3. Avoid misallocated headcount expenditure.
    """
    core = df[df['created_at'] >= '2025-01-01'].copy()
    num_quarters = 6.0  # 18 months / 3 months per quarter

    # 1. Billing Misrouting Waste
    bp_assigned = core[core['assigned_team'] == 'Billing']
    total_bp_assigned = len(bp_assigned)
    misrouted_bp = len(bp_assigned[bp_assigned['resolving_team'] != 'Billing'])
    misrouting_rate_current = misrouted_bp / total_bp_assigned  # ~33.5% routed elsewhere; 41.5% in text tags

    # Transfers generated by Billing assigned tickets
    bp_transfers = bp_assigned['transfers_recorded'].sum()
    bp_transfer_cost_total = bp_transfers * TRANSFER_COST_INR
    bp_transfer_cost_quarterly = bp_transfer_cost_total / num_quarters

    # SLA breaches in Billing assigned queue
    bp_breaches = bp_assigned['is_sla_breach'].sum()
    bp_breach_penalty_total = bp_breaches * SLA_BREACH_PENALTY_INR
    bp_breach_penalty_quarterly = bp_breach_penalty_total / num_quarters

    # 2. Double-Dipping Policy Violation (Refund + Replacement on same order)
    dd_tickets = core[core['is_double_dipped_order']]
    dd_orders_count = dd_tickets['order_id'].nunique()
    dd_leakage_total = dd_tickets['refund_amount_inr'].sum()
    dd_leakage_quarterly = dd_leakage_total / num_quarters

    # Total process savings per quarter
    total_quarterly_process_savings = bp_transfer_cost_quarterly + bp_breach_penalty_quarterly + dd_leakage_quarterly
    total_annual_process_savings = total_quarterly_process_savings * 4.0

    # Avoided hire savings
    quarterly_avoided_hire_cost = ANNUAL_TWO_HIRES_COST_INR / 4.0

    savings_breakdown = {
        'Avoidable_Billing_Transfers_Quarterly_INR': round(bp_transfer_cost_quarterly, 2),
        'Avoidable_SLA_Breach_Penalties_Quarterly_INR': round(bp_breach_penalty_quarterly, 2),
        'Double_Dipping_Leakage_Quarterly_INR': round(dd_leakage_quarterly, 2),
        'Total_Quarterly_Process_Savings_INR': round(total_quarterly_process_savings, 2),
        'Total_Annual_Process_Savings_INR': round(total_annual_process_savings, 2),
        'Avoided_Billing_Hire_Cost_Annual_INR': ANNUAL_TWO_HIRES_COST_INR,
        'Current_Billing_Misrouting_Rate': f"{misrouting_rate_current:.1%}",
        'Target_Billing_Misrouting_Rate': "5.0%",
        'Double_Dip_Orders_Count': dd_orders_count
    }

    return savings_breakdown


def run_full_analysis():
    input_csv = "outputs/tickets_categorised.csv"
    if not os.path.exists(input_csv):
        raise FileNotFoundError(f"Input categorised dataset not found: {input_csv}")

    df = pd.read_csv(input_csv)
    print("Executing Phase 5: Business Analysis & Headcount Hypothesis Testing...\n")

    # 1. Test Headcount Rule
    rule_df = analyze_headcount_rule(df)
